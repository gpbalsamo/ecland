SUBROUTINE SRFWVAPOR(KIDIA,KFDIA,KLON,KLEVS,&
 & PTSPHY,&
 & PWSAM1M,PTSA,&
 & PSSDP3,&
 & YDSOIL,YDCST,&
 & LDLAND,&
 & PRHSW)

